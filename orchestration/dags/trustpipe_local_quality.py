"""Airflow smoke DAG for the local TrustPipe stack.

The production ingest/dbt tasks require Snowflake credentials. This DAG gives the
local Airflow app a runnable workflow that documents the same quality sequence
without opening external connections.
"""
from __future__ import annotations

from datetime import datetime

from airflow import DAG
from airflow.operators.bash import BashOperator


with DAG(
    dag_id="trustpipe_local_quality",
    description="Local TrustPipe smoke workflow",
    start_date=datetime(2024, 1, 1),
    schedule=None,
    catchup=False,
    tags=["trustpipe", "local"],
) as dag:
    contracts = BashOperator(
        task_id="contract_layer",
        bash_command="echo 'Data contracts configured for batch, weather, and stream sources'",
    )

    dbt_parse = BashOperator(
        task_id="dbt_parse_layer",
        bash_command="echo 'dbt parse validated by make quality-local on the host'",
    )

    scorecard = BashOperator(
        task_id="scorecard_layer",
        bash_command="echo 'Reliability scorecard generated by make scorecard'",
    )

    contracts >> dbt_parse >> scorecard
